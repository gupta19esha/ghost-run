// Measures fork scores before one is ruled: every fork of the four player types on several seeds,
// scored by each score in agent/rank.js, and what each one puts at the top.
//
// node scripts/measure-rank.mjs [--seeds=1-10] [--out=FILE]
// Prints a Markdown report, and writes it to FILE as well when --out is given. Progress on stderr.

import { writeFileSync } from "node:fs";
import { forksOf, order, surpriseMeasures, SCORES, UNITS, SHOCK_MONTH } from "../agent/rank.js";
import { typeSave, PLAYER_TYPES } from "./player-saves.mjs";
import { formatRupees } from "../vendor/dry-run-engine/text/render.js";

const arg = (name, fallback) => process.argv.find((a) => a.startsWith(`--${name}=`))?.split("=")[1] ?? fallback;
const [first, last] = arg("seeds", "1-10").split("-").map(Number);
const SEEDS = Array.from({ length: (last ?? first) - first + 1 }, (_, i) => first + i);
const TOP = 5;
const KEYS = ["netWorth", "safety", "freedom", "life"];
const NAMES = { netWorth: "Net worth", safety: "Safety", freedom: "Freedom", life: "Life" };

const started = Date.now();
const saves = [];
for (const type of PLAYER_TYPES) {
  for (const seed of SEEDS) {
    saves.push({ type, seed, forks: forksOf(typeSave(type, seed)) });
    process.stderr.write(`${type} seed ${seed}: ${((Date.now() - started) / 1000).toFixed(0)}s\n`);
  }
}
const all = saves.flatMap((s) => s.forks.map((f) => ({ ...f, type: s.type, seed: s.seed })));
for (const s of saves) for (const name of Object.keys(SCORES)) s[name] = order(s.forks, name);

const quantiles = (values, ps) => { const a = [...values].sort((x, y) => x - y); return ps.map((p) => a[Math.floor(p * (a.length - 1))]); };
const show = (k, v) => (k === "netWorth" ? formatRupees(Math.round(v)) : v.toFixed(1));
const pct = (n, d) => `${(100 * n / d).toFixed(1)}%`;
const fork = (f) => `${f.real}→${f.option}`;
const gapPath = (f, k) => f.fork.divergence.filter((r) => r.month >= f.month)
  .map((r) => (k === "netWorth" ? Math.round(r[k] / 1000) : Math.round(r[k]))).join(" ");
const rankCorr = (a, b) => {
  const rank = (v) => { const r = []; v.map((x, i) => [x, i]).sort((p, q) => p[0] - q[0]).forEach(([, i], j) => (r[i] = j)); return r; };
  const ra = rank(a), rb = rank(b), n = a.length, m = (n - 1) / 2;
  let c = 0, va = 0, vb = 0;
  for (let i = 0; i < n; i++) { c += (ra[i] - m) * (rb[i] - m); va += (ra[i] - m) ** 2; vb += (rb[i] - m) ** 2; }
  return c / Math.sqrt(va * vb);
};
const component = (reason) => reason.split(":")[0];

const lines = [];
const out = (...l) => lines.push(...l);
const table = (head, rows) => out(`| ${head.join(" | ")} |`, `|${head.map(() => "---").join("|")}|`, ...rows.map((r) => `| ${r.join(" | ")} |`), "");

out("# Fork scores, measured", "",
  `${saves.length} saves: the four player types on seeds ${first}–${last ?? first}. ${all.length} forks, every choice to every alternative offered there.`,
  `Substitution rule: the ruled default. Engine: vendor/dry-run-engine, logic unchanged. Generated by scripts/measure-rank.mjs in ${((Date.now() - started) / 1000).toFixed(0)}s.`, "");

out("## 1. How far forks move each figure", "",
  "Ghost minus real, absolute. \"End\" is month 24; \"widest\" is the largest gap anywhere after the fork.", "");
const ps = [0.25, 0.5, 0.75, 0.9, 0.99];
table(["Figure", "", ...ps.map((p) => `p${p * 100}`)], KEYS.flatMap((k) => [
  [NAMES[k], "end", ...quantiles(all.map((f) => Math.abs(f.features.end[k])), ps).map((v) => show(k, v))],
  ["", "widest", ...quantiles(all.map((f) => Math.max(...f.fork.divergence.map((r) => Math.abs(r[k])))), ps).map((v) => show(k, v))],
]));
out(`UNITS in agent/rank.js are the p75 of the widest gap, rounded: ${KEYS.map((k) => `${NAMES[k]} ${show(k, UNITS[k])}`).join(", ")}.`,
  "Safety and Freedom do not move at all on about half of forks; Life moves on nearly every fork, and never far.", "");
out("Rank correlation of the end net worth gap with each bar's end gap, all forks: " +
  KEYS.slice(1).map((k) => `${NAMES[k]} ${rankCorr(all.map((f) => Math.abs(f.features.end.netWorth)), all.map((f) => Math.abs(f.features.end[k]))).toFixed(2)}`).join(", ") +
  ". The bars carry information the money gap does not.", "");

out("## 2. The obvious score: net worth gap at month 24", "");
const decisionCounts = (name) => {
  const count = new Map();
  for (const s of saves) for (const f of s[name].slice(0, TOP)) count.set(f.decisionId, (count.get(f.decisionId) || 0) + 1);
  return [...count].sort((a, b) => b[1] - a[1]);
};
out(`Decisions in each save's top ${TOP}, counted over ${saves.length} saves (${saves.length * TOP} places): ` +
  decisionCounts("net-worth-gap").map(([d, c]) => `${d} ${c}`).join(", ") + ".", "");
// The same decision at the top for every player, and two options of one decision filling two places
const habits = (name) => {
  const everyType = [...new Set(saves.flatMap((s) => s[name].slice(0, TOP).map((f) => f.decisionId)))]
    .filter((d) => PLAYER_TYPES.every((type) => saves.some((s) => s.type === type && s[name].slice(0, TOP).some((f) => f.decisionId === d))));
  const doubled = saves.filter((s) => new Set(s[name].slice(0, TOP).map((f) => f.decisionId)).size < TOP).length;
  return [`In some top ${TOP} of all four types: ${everyType.join(", ") || "none"}. ` +
    `Saves whose top ${TOP} holds two options of the same decision: ${doubled} of ${saves.length}.`];
};
const sameness = (name) => PLAYER_TYPES.map((type) => {
  const sets = saves.filter((s) => s.type === type).map((s) => s[name].slice(0, TOP).map(fork).sort().join(", "));
  const common = new Map(); for (const set of sets) common.set(set, (common.get(set) || 0) + 1);
  const [set, n] = [...common].sort((a, b) => b[1] - a[1])[0];
  return [type, String(new Set(sets).size), `${n} of ${sets.length}`, set];
});
table(["Type", `Distinct top ${TOP}s over ${SEEDS.length} seeds`, "Most common", "Most common top 5"], sameness("net-worth-gap"));
out(...habits("net-worth-gap"), "");

out("## 3. Unexpected things, one measure each", "",
  `A fork counts below when the measure is at least one unit. Shock: month ${SHOCK_MONTH}, the layoff and the bottom of the market fall.`, "");
const counted = {};
for (const f of all) {
  const hits = surpriseMeasures(f.features).filter(([, v]) => v >= 1).map(([name]) => name);
  for (const h of hits) (counted[h] ||= []).push(f);
}
const MEANING = {
  reversal: "the gap held on the other side for six months or more, and both that and the end gap are a unit or more",
  shock: "months 21 to 24 moved the gap a unit more than months 18 to 21 did plus the gap already open at month 21 (forks at month 18 or earlier)",
  "quiet-money": "a bar ends a unit apart while net worth ends close",
  "trade-off": "net worth and Safety or Freedom end a unit apart, in opposite directions",
};
const lifeTrade = all.filter((f) => { const { end } = f.features; const money = Math.abs(end.netWorth) / UNITS.netWorth; return Math.sign(end.life) === -Math.sign(end.netWorth) && Math.min(money, Math.abs(end.life) / UNITS.life) >= 1; });
table(["Measure", "Forks", "Saves with one", "Decisions"], Object.entries(counted).sort((a, b) => b[1].length - a[1].length).map(([name, fs]) => [
  name, `${fs.length} (${pct(fs.length, all.length)})`, `${new Set(fs.map((f) => f.type + f.seed)).size} of ${saves.length}`, [...new Set(fs.map((f) => f.decisionId))].sort().join(" "),
]));
const silent = Object.keys(MEANING).filter((m) => !Object.keys(counted).some((name) => name.startsWith(`${m}:`)));
if (silent.length) out(`No fork reaches a unit on: ${silent.join(", ")}.`, "");
out(...Object.entries(MEANING).map(([k, v]) => `- ${k}: ${v}.`), "",
  `Left out: the same trade-off on Life, ${lifeTrade.length} forks (${pct(lifeTrade.length, all.length)}), decisions ${[...new Set(lifeTrade.map((f) => f.decisionId))].sort().join(" ")}. ` +
  "Spending for Life is the trade the sheet writes into nearly every option; counted, it filled most of Spender's top five with \"richer, enjoying less\".", "");
const crossed = all.filter((f) => KEYS.some((k) => { const e = f.features.end[k]; return Math.abs(e) >= UNITS[k] / 4 && f.fork.divergence.some((r) => r.month >= f.month && Math.sign(r[k]) === -Math.sign(e) && Math.abs(r[k]) >= UNITS[k] / 2); }));
const ghostBetter = crossed.filter((f) => KEYS.some((k) => f.features.end[k] > 0 && f.fork.divergence.some((r) => r.month >= f.month && r[k] < -UNITS[k] / 2)));
out(`Real reversals are rare: ${crossed.length} forks (${pct(crossed.length, all.length)}) have a gap of half a unit on one side that ends a quarter unit on the other. ` +
  `${ghostBetter.length} of them (${pct(ghostBetter.length, all.length)} of all forks) end with the ghost ahead after it was behind, the "looked worse, ended better" case.`, "");

out("## 4. The proposed score: surprise", "",
  "The largest of the four measures in section 3, each in units: reversal, shock, quiet-money, trade-off. The money gap on its own scores nothing. Not applied: SCORE in agent/rank.js is still null.", "");
out(`Decisions in each save's top ${TOP}, counted over ${saves.length} saves: ` + decisionCounts("surprise").map(([d, c]) => `${d} ${c}`).join(", ") + ".", "");
table(["Type", `Distinct top ${TOP}s over ${SEEDS.length} seeds`, "Most common", "Most common top 5"], sameness("surprise"));
out(...habits("surprise"), "");
const clearing = PLAYER_TYPES.map((type) => {
  const counts = saves.filter((s) => s.type === type).map((s) => s.surprise.filter((f) => f.score >= 1).length);
  return [type, String(quantiles(counts, [0.5])[0]), `${Math.min(...counts)}–${Math.max(...counts)}`];
});
out("Forks per save scoring a unit or more, the point where something unexpected is a unit's size:", "");
table(["Type", "Median", "Range over seeds"], clearing);
const reasons = new Map();
for (const s of saves) for (const f of s.surprise.slice(0, TOP)) reasons.set(component(f.reason), (reasons.get(component(f.reason)) || 0) + 1);
out(`What wins the top ${TOP} places: ` + [...reasons].sort((a, b) => b[1] - a[1]).map(([r, n]) => `${r} ${n}`).join(", ") + ".", "");
const overlap = saves.reduce((n, s) => n + s.surprise.slice(0, TOP).filter((f) => s["net-worth-gap"].slice(0, TOP).some((g) => g.option === f.option && g.monthIndex === f.monthIndex)).length, 0);
out(`Overlap with the net worth top ${TOP}: ${overlap} of ${saves.length * TOP} places.`, "");

out(`### What it surfaces, seed ${first}`, "",
  "Gap paths are ghost minus real from the fork month to month 24, net worth in thousands, bars in points.", "");
for (const type of PLAYER_TYPES) {
  const s = saves.find((x) => x.type === type && x.seed === first);
  out(`**${type}**`, "");
  table(["#", "Fork", "Month", "Score", "Why", "Path of the figure that scored", "End net worth gap"], s.surprise.slice(0, TOP).map((f, i) => {
    const k = f.reason.split(":")[1] ?? "netWorth";
    return [String(i + 1), fork(f), String(f.month), f.score.toFixed(2), f.reason, `${NAMES[k]}: ${gapPath(f, k)}`, formatRupees(Math.round(f.features.end.netWorth))];
  }));
}

out("### What it buries", "", `Where each save's net worth top ${TOP} lands under surprise, out of that save's forks:`, "");
const buried = [];
for (const s of saves.filter((x) => x.seed === first)) {
  for (const f of s["net-worth-gap"].slice(0, TOP)) {
    const at = s.surprise.findIndex((g) => g.option === f.option && g.monthIndex === f.monthIndex);
    buried.push([s.type, fork(f), formatRupees(Math.round(f.features.end.netWorth)), `${at + 1} of ${s.surprise.length}`, s.surprise[at].score.toFixed(2), s.surprise[at].reason ?? "nothing"]);
  }
}
table(["Type", "Fork", "End net worth gap", "Surprise rank", "Score", "Why"], buried);
const medianRank = quantiles(saves.flatMap((s) => s["net-worth-gap"].slice(0, TOP).map((f) => s.surprise.findIndex((g) => g.option === f.option && g.monthIndex === f.monthIndex) + 1)), [0.5])[0];
out(`Across all ${saves.length} saves the net worth top ${TOP} has a median surprise rank of ${medianRank}.`, "");

const text = lines.join("\n");
console.log(text);
const file = arg("out", null);
if (file) writeFileSync(file, text + "\n");
