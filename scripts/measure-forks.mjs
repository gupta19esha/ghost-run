// How often a fork leaves the ghost unable to follow a later real choice (rule 29, maths doc
// section 10), and what each substitution rule does about it. Reports; changes nothing.
//
// Usage, from the repo root:
//   node scripts/measure-forks.mjs                 the four player types on seed 1, then 200
//                                                  random players (about 14 minutes; --random=0 takes 15s)
//   node scripts/measure-forks.mjs --seeds=1-10    the same on seeds 1 to 10
//   node scripts/measure-forks.mjs --random=500    secondary: 500 random players (default 200, 0 for none)
//   node scripts/measure-forks.mjs --out=FILE      also write the report to FILE
//
// The four player types are the population asked about. Of them only Spender takes D16-A, and
// none takes D20-D or D28-B, so random players (the calibration harness's randomPicker) follow as
// a secondary measure of the paths rule 29 actually acts on.
//
// For every save, every choice in its save and every other option offered there, fork
// the save. A rule only matters once a real choice is withdrawn, and every rule keeps the real
// choice until then, so each fork runs first under keep-real-or-stop: that finds the first
// withdrawn choice, whatever the rule. Forks that hit one run again under every rule, to see what
// each fallback picks, whether it withdraws further choices, and how far it moves the outcome.

import { writeFileSync } from "node:fs";

import { fork, alternativesAt, STRATEGIES } from "../runner/fork.js";
import { getDecision } from "../vendor/dry-run-engine/engine/index.js";
import { typeSave, randomSave, PLAYER_TYPES, DECISION_ORDER } from "./player-saves.mjs";

const args = Object.fromEntries(process.argv.slice(2).map((a) => a.replace(/^--/, "").split("=")));
const seeds = parseSeeds(args.seeds || "1");
const randomCount = Number(args.random ?? 200);
const RULES = Object.keys(STRATEGIES);
const FALLBACKS = RULES.filter((r) => r !== "keep-real-or-stop");
const started = Date.now();

const monthOf = (decisionId) => getDecision(decisionId).month;

// Every fork of every save: each choice, against every other option offered there
function collect(saves) {
  const forks = [];
  for (const [n, { label, save }] of saves.entries()) {
    process.stderr.write(`\r${label}, seed ${save.seed}: save ${n + 1} of ${saves.length}   `);
    for (let index = 0; index < save.choices.length; index++) {
      for (const alternative of alternativesAt(save, index)) {
        const first = fork(save, index, alternative, { substitution: "keep-real-or-stop" });
        const record = {
          seed: save.seed, type: label, index, decision: DECISION_ORDER[index], real: save.choices[index], alternative,
          laterChoices: save.choices.length - index - 1,
          withdrawn: first.ghost.substitutions[0] || null,
          byRule: {},
        };
        if (record.withdrawn) {
          record.withdrawn.distanceMonths = record.withdrawn.month - monthOf(record.decision);
          record.withdrawn.distanceChoices = record.withdrawn.index - index;
          for (const rule of FALLBACKS) {
            const { ghost, divergence } = fork(save, index, alternative, { substitution: rule });
            record.byRule[rule] = { substitutions: ghost.substitutions, end: divergence.at(-1) };
          }
          record.byRule["keep-real-or-stop"] = { substitutions: first.ghost.substitutions, end: first.divergence.at(-1) };
        }
        forks.push(record);
      }
    }
  }
  return forks;
}

const typeForks = collect(seeds.flatMap((seed) => PLAYER_TYPES.map((type) => ({ label: type, save: typeSave(type, seed) }))));
const randomForks = collect(Array.from({ length: randomCount }, (_, i) => ({ label: "random", save: randomSave(i + 1) })));

const report = [
  "# Fork substitution report",
  "",
  `Engine: vendor/dry-run-engine, unchanged. Generated by scripts/measure-forks.mjs in ${((Date.now() - started) / 1000).toFixed(0)}s.`,
  "A fork is one choice of a Chapter 1 save replaced by another option offered there; every fork of",
  "every save is run. A choice is withdrawn when the ghost reaches a later decision and no longer",
  "offers the option the player really chose (rule 29).",
  "",
  render(typeForks, `Part A. The four player types, seeds ${seeds.join(", ")}`, [...PLAYER_TYPES]),
  randomCount ? render(randomForks, `Part B. ${randomCount} random players, seeds 1 to ${randomCount}. Secondary: paths the types never take`, ["random"]) : "",
].join("\n");
process.stdout.write(report);
if (args.out) writeFileSync(args.out, report);

function render(forks, title, labels) {
  const out = [];
  const line = (s = "") => out.push(s);
  const hit = forks.filter((f) => f.withdrawn);
  const laterChecked = forks.reduce((n, f) => n + f.laterChoices, 0);

  line(`## ${title}`);
  line();
  line(`${forks.length} forks.`);
  line();

  line("### 1. How often a later real choice is withdrawn");
  line();
  line("| Measure | Count | Rate |");
  line("|---|---|---|");
  line(`| Forks where at least one later real choice is not offered on the ghost | ${hit.length} of ${forks.length} | ${pct(hit.length, forks.length)} |`);
  line(`| Later real choices withdrawn, first per fork, of all later choices the ghosts faced | ${hit.length} of ${laterChecked} | ${pct(hit.length, laterChecked)} |`);
  line();
  line("By player:");
  line();
  line("| Type | Forks | Withdrawn | Rate |");
  line("|---|---|---|---|");
  for (const type of labels) {
    const mine = forks.filter((f) => f.type === type);
    const h = mine.filter((f) => f.withdrawn).length;
    line(`| ${type} | ${mine.length} | ${h} | ${pct(h, mine.length)} |`);
  }
  line();

  line("### 2. Which decisions cause it");
  line();
  line("Forked at, the fork that leaves the ghost unable to follow:");
  line();
  line("| Fork decision | Forks there | Withdrawing | Rate |");
  line("|---|---|---|---|");
  for (const decision of DECISION_ORDER) {
    const there = forks.filter((f) => f.decision === decision);
    const h = there.filter((f) => f.withdrawn).length;
    if (h > 0) line(`| ${decision} | ${there.length} | ${h} | ${pct(h, there.length)} |`);
  }
  line(`| Every other decision | ${forks.filter((f) => !hit.some((h) => h.decision === f.decision)).length} | 0 | 0% |`);
  line();
  line("The forks, real option to alternative, and the real choice each withdraws:");
  line();
  line("| Fork | Withdraws | Types | Forks |");
  line("|---|---|---|---|");
  for (const [key, group] of groupBy(hit, (f) => `${f.real} → ${f.alternative} | ${f.withdrawn.real}`)) {
    line(`| ${key} | ${[...new Set(group.map((f) => f.type))].join(", ")} | ${group.length} |`);
  }
  line();
  line("Withdrawn, the later real choice the ghost cannot take:");
  line();
  line("| Real choice | Times | Why it is not offered |");
  line("|---|---|---|");
  for (const [real, group] of groupBy(hit, (f) => f.withdrawn.real)) {
    line(`| ${real} | ${group.length} | ${why(real)} |`);
  }
  line();

  line("### 3. How far after the fork");
  line();
  const months = hit.map((f) => f.withdrawn.distanceMonths).sort((a, b) => a - b);
  const choices = hit.map((f) => f.withdrawn.distanceChoices).sort((a, b) => a - b);
  if (hit.length) {
    line(`Months from the fork to the withdrawn choice: min ${months[0]}, median ${median(months)}, max ${months.at(-1)}.`);
    line(`Choices from the fork to the withdrawn choice: min ${choices[0]}, median ${median(choices)}, max ${choices.at(-1)}.`);
    line();
    line("| Fork month → withdrawn month | Months apart | Forks |");
    line("|---|---|---|");
    for (const [key, group] of groupBy(hit, (f) => `${f.decision} (month ${monthOf(f.decision)}) → ${f.withdrawn.decision_id} (month ${f.withdrawn.month}) | ${f.withdrawn.distanceMonths}`)) {
      line(`| ${key} | ${group.length} |`);
    }
  } else {
    line("No fork withdraws a later choice.");
  }
  line();

  line("### 4. What each fallback takes");
  line();
  line("Every rule keeps the real choice while the ghost offers it, so they differ only here.");
  line("keep-real-or-stop ends the ghost at the withdrawn choice instead of choosing.");
  line();
  line(`| Withdrawn | Ghost offers | ${FALLBACKS.join(" | ")} |`);
  line(`|---|---|${FALLBACKS.map(() => "---").join("|")}|`);
  for (const [, group] of groupBy(hit, (f) => `${f.withdrawn.real}|${f.withdrawn.offered.join(",")}`)) {
    const f = group[0];
    const picks = FALLBACKS.map((rule) => label(f.byRule[rule].substitutions[0].chosen));
    line(`| ${label(f.withdrawn.real)} | ${f.withdrawn.offered.join(", ")} | ${picks.join(" | ")} |`);
  }
  line();
  line("Further real choices each fallback's pick withdraws later in the same ghost:");
  line();
  line("| Rule | Forks with a second withdrawal | Total substitutions |");
  line("|---|---|---|");
  for (const rule of FALLBACKS) {
    const subs = hit.map((f) => f.byRule[rule].substitutions.length);
    line(`| ${rule} | ${subs.filter((n) => n > 1).length} | ${subs.reduce((a, b) => a + b, 0)} |`);
  }
  line();
  const minOffered = Math.min(...hit.flatMap((f) => Object.values(f.byRule).flatMap((r) => r.substitutions.map((s) => s.offered.length))));
  if (hit.length) line(`Fewest options any ghost was offered at a withdrawn choice: ${minOffered} (rule 29 promises at least two).`);
  line();

  line("### 5. How much the rule moves the answer");
  line();
  line("Ghost minus real at the last month both closed, for the forks that hit a withdrawn choice:");
  line("month 24 for the three fallbacks, the month before the withdrawn choice for keep-real-or-stop.");
  line("Spread is the largest gap between two fallbacks' answers for the same fork: how much the");
  line("ruling changes what the player is told.");
  line();
  line(`| Fork | Withdraws | Forks | ${FALLBACKS.map((r) => `${r}, net worth`).join(" | ")} | Spread, median | Spread, max | keep-real-or-stop, net worth at its last month |`);
  line(`|---|---|---|${FALLBACKS.map(() => "---").join("|")}|---|---|---|`);
  const spreadOf = (f) => {
    const values = FALLBACKS.map((r) => f.byRule[r].end.netWorth);
    return Math.max(...values) - Math.min(...values);
  };
  const spreads = hit.map(spreadOf);
  const med = (values) => median([...values].sort((a, b) => a - b));
  for (const [, group] of groupBy(hit, (f) => `${f.real} → ${f.alternative} | ${f.withdrawn.real}`)) {
    const f = group[0];
    const perRule = FALLBACKS.map((r) => rupees(med(group.map((g) => g.byRule[r].end.netWorth))));
    const stopEnds = group.map((g) => g.byRule["keep-real-or-stop"].end);
    line(`| ${f.real} → ${f.alternative} | ${f.withdrawn.real} | ${group.length} | ${perRule.join(" | ")} | ${rupees(med(group.map(spreadOf)))} | ${rupees(Math.max(...group.map(spreadOf)))} | month ${med(stopEnds.map((e) => e.month))}: ${rupees(med(stopEnds.map((e) => e.netWorth)))} |`);
  }
  line();
  line("Net worth columns are medians over the forks in the row.");
  if (hit.length) {
    line();
    line(`Spread across fallbacks, every fork: median ${rupees(med(spreads))}, max ${rupees(Math.max(...spreads))}.`);
    line();
    line("The same forks on the four bars at the last month, ghost minus real, median over the forks:");
    line();
    line("| Rule | Net worth | Safety | Freedom | Life |");
    line("|---|---|---|---|---|");
    for (const rule of RULES) {
      const ends = hit.map((f) => f.byRule[rule].end);
      const med = (k) => median(ends.map((e) => e[k]).sort((a, b) => a - b));
      line(`| ${rule} | ${rupees(med("netWorth"))} | ${med("safety").toFixed(1)} | ${med("freedom").toFixed(1)} | ${med("life").toFixed(1)} |`);
    }
  }
  line();
  return out.join("\n");
}

function why(optionId) {
  const [decisionId] = optionId.split("-");
  const option = getDecision(decisionId).options[optionId];
  if (option.modifies_commitment?.length) return `Changes ${option.modifies_commitment.join(", ")}: offered only while one of their saving commitments runs`;
  if (option.requires === "index") return "requires index: D16-A's monthly investment running";
  if (option.requires === "no_index") return "requires no_index: D16-A's monthly investment not running";
  return "Precondition";
}

function label(optionId) {
  if (optionId === null) return "stop";
  const [decisionId] = optionId.split("-");
  return `${optionId}, ${getDecision(decisionId).options[optionId].option_label}`;
}

function groupBy(items, key) {
  const groups = new Map();
  for (const item of items) {
    const k = key(item);
    if (!groups.has(k)) groups.set(k, []);
    groups.get(k).push(item);
  }
  return [...groups.entries()].sort((a, b) => b[1].length - a[1].length || a[0].localeCompare(b[0]));
}

function median(sorted) {
  if (!sorted.length) return NaN;
  const mid = Math.floor(sorted.length / 2);
  return sorted.length % 2 ? sorted[mid] : (sorted[mid - 1] + sorted[mid]) / 2;
}

function pct(n, d) {
  return d ? `${((100 * n) / d).toFixed(1)}%` : "n/a";
}

function rupees(n) {
  return `${n < 0 ? "-" : ""}${Math.round(Math.abs(n)).toLocaleString("en-IN")}`;
}

function parseSeeds(text) {
  return text.split(",").flatMap((part) => {
    const [a, b] = part.split("-").map(Number);
    return b ? Array.from({ length: b - a + 1 }, (_, i) => a + i) : [a];
  });
}
